    /**
     * reinicia la captura de huellas
     * @param msg 
     */
    public void reiniciar(String msg){
    
        
         
        JOptionPane.showMessageDialog(this, msg);
        
        this.setVisible(false);
        
        capturaModel.stopCaptureM();
        
        Captura nuevac = new Captura(capturaModel.ns,capturaModel.n_huella);
        
        //nuevac.show();
        nuevac.setVisible(true);
        //this.disable();
        
    
    }
    
    
    /**
     * Miestra la Huella en la pantall recibe la imagen del huella
     * 
     * @param image 
     */
    
    public void DibujarHuella(Image image) {
        lblHuella.setIcon(new ImageIcon(
                image.getScaledInstance(lblHuella.getWidth(), lblHuella.getHeight(), Image.SCALE_DEFAULT)));
        repaint();
    }


    

    /**
     * 
     * Cambia el color un elemento de la interfaz cuando el dedo esta sobre el huellero
     * 
     */
    public void pintarDedoPuesto() {
            txtDedo.setBackground(Color.green);
    }

    /**
     * Cambia el color de un elemento de la interfaz cuando el dedo no esta sobre el huellero
     */
    public void pintarDedonoPuesto() {
           txtDedo.setBackground(Color.yellow);
    }

    /**
     * finalzia el proceso de captura de huella
     * @param msg 
     */
    public void closeCapture(String msg) {

        JOptionPane.showMessageDialog(this, msg);
        
        capturaModel.closeCaptureM();
        this.setVisible(false);
        this.dispose();
    }

